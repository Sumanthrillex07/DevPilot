package com.devpilot.backend.services.ai;

import com.devpilot.backend.dto.ChatMessageResponse;
import com.devpilot.backend.dto.CitationDto;
import com.devpilot.backend.entities.ChatMessage;
import com.devpilot.backend.entities.MessageRole;
import com.devpilot.backend.repositories.ChatMessageRepository;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.ai.chat.client.ChatClient;
import org.springframework.ai.chat.model.ChatModel;
import org.springframework.http.MediaType;
import org.springframework.stereotype.Component;
import org.springframework.web.servlet.mvc.method.annotation.SseEmitter;

import java.util.List;
import java.util.UUID;

/**
 * Handles LLM streaming generation and Server-Sent Events (SSE) push to the client.
 *
 * <p><b>SSE Protocol:</b>
 * <ul>
 *   <li>{@code event: user_message} — Echoes the saved user message to the UI.</li>
 *   <li>{@code event: token} — Real-time incremental token chunk as generated by the LLM.</li>
 *   <li>{@code event: assistant_message} — The full persisted assistant response with line citations.</li>
 *   <li>{@code event: done} — Payload {@code [DONE]} signaling that the stream is closing cleanly.</li>
 * </ul>
 */
@Component
@RequiredArgsConstructor
@Slf4j
public class ChatStreamHandler {

    private final ChatModel chatModel;
    private final ChatMessageRepository chatMessageRepository;
    private final CitationMapper citationMapper;

    /**
     * Initiates a reactive streaming generation pipeline and returns an {@link SseEmitter}.
     */
    public SseEmitter stream(
            UUID sessionId,
            ChatMessageResponse savedUserMessage,
            List<CitationDto> citations,
            String systemPrompt,
            String userPrompt) {

        SseEmitter emitter = new SseEmitter(RagSettings.STREAM_TIMEOUT_MS);
        StringBuilder fullReply = new StringBuilder();

        try {
            // 1. Immediately emit the persisted user message
            emitter.send(SseEmitter.event()
                    .name("user_message")
                    .data(savedUserMessage));

            // 2. Stream tokens from the ChatModel using ChatClient
            ChatClient.builder(chatModel)
                    .build()
                    .prompt()
                    .system(systemPrompt)
                    .user(userPrompt)
                    .stream()
                    .content()
                    .doOnNext(token -> appendToken(emitter, fullReply, token))
                    .doOnError(err -> {
                        log.error("Chat stream error for session {}", sessionId, err);
                        emitter.completeWithError(err);
                    })
                    .doOnComplete(() -> completeStream(emitter, sessionId, fullReply, citations))
                    .subscribe();

        } catch (Exception ex) {
            log.error("Failed to start SSE stream for session {}", sessionId, ex);
            emitter.completeWithError(ex);
        }

        return emitter;
    }

    private void appendToken(SseEmitter emitter, StringBuilder fullReply, String token) {
        if (token == null) {
            return;
        }
        fullReply.append(token);
        try {
            emitter.send(SseEmitter.event()
                    .name("token")
                    .data(token, MediaType.APPLICATION_JSON));
        } catch (Exception ex) {
            throw new IllegalStateException("Failed to send token event", ex);
        }
    }

    private void completeStream(
            SseEmitter emitter,
            UUID sessionId,
            StringBuilder fullReply,
            List<CitationDto> citations) {
        try {
            // Persist the completed assistant message with citations JSON
            ChatMessage assistant = chatMessageRepository.save(ChatMessage.builder()
                    .sessionId(sessionId)
                    .role(MessageRole.ASSISTANT)
                    .content(fullReply.toString())
                    .citations(citationMapper.toJson(citations))
                    .build());

            // Emit the complete assistant message payload with structured citations
            emitter.send(SseEmitter.event()
                    .name("assistant_message")
                    .data(ChatMessageResponse.from(assistant, citations)));

            // Signal stream completion
            emitter.send(SseEmitter.event()
                    .name("done")
                    .data("[DONE]"));

            emitter.complete();
        } catch (Exception ex) {
            log.error("Failed to complete stream for session {}", sessionId, ex);
            emitter.completeWithError(ex);
        }
    }
}
